func GetPostRegionByID(id int) *PostRegion {
	for _, region := range PostRegions {
		if region.ID == id {
			return &region
		}
	}
	return nil
}

func RandomPostByRegion(region *PostRegion) *Post {
	trading := rand.Intn(100) >= 50
	var posts []*Post
	if trading {
		posts = getPostsWithCategoryAndLanguage(Trading, region.Language)
	} else {
		posts = getPostsWithCategoryAndLanguage(General, region.Language)
	}
	if len(posts) == 0 {
		return nil
	}
	return posts[rand.Intn(len(posts))]
}

func getPostsWithCategoryAndLanguage(category Category, language string) []*Post {
	posts := make([]*Post, 0)
	for _, post := range Posts {
		if post.Category == category && post.Language == language {
			posts = append(posts, &post)
		}
	}
	return posts
}
